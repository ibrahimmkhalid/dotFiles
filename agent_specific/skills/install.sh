#!/bin/bash
# links every skill in this directory into each agent's skills directory
# opencode ignores "disable-model-invocation", so those skills are installed as
# opencode commands instead, which only the user can invoke
# relies on OPENCODE_DISABLE_CLAUDE_CODE_SKILLS=1 from zshrc, otherwise opencode
# picks them back up out of ~/.claude/skills
# pass "clean" to remove the links again
set -e

skills_dir="$(cd "$(dirname "$0")" && pwd -P)"
agent_dirs=(
  "$HOME/.claude/skills"
  "$HOME/.codex/skills"
  "$HOME/.config/opencode/skills"
  "$HOME/.cursor/skills"
)
opencode_skills_dir="$HOME/.config/opencode/skills"
opencode_command_dir="$HOME/.config/opencode/command"

frontmatter() {
  awk 'NR>1 && /^---$/{exit} NR>1' "$1/SKILL.md"
}

user_only() {
  frontmatter "$1" | grep -qE '^disable-model-invocation:[[:space:]]*true[[:space:]]*$'
}

for agent_dir in "${agent_dirs[@]}"; do
  [ "$1" = "clean" ] || mkdir -p "$agent_dir"
  for skill in "$skills_dir"/*/; do
    skill="${skill%/}"
    [ -d "$skill" ] || continue
    dest="$agent_dir/$(basename "$skill")"

    if [ "$1" = "clean" ] || { [ "$agent_dir" = "$opencode_skills_dir" ] && user_only "$skill"; }; then
      if [ -L "$dest" ]; then
        rm -f "$dest"
        echo "unlinked $dest"
      fi
    elif [ -e "$dest" ] && [ ! -L "$dest" ]; then
      echo "skipped $dest, already exists and is not a link" >&2
    elif [ "$(readlink "$dest")" != "$skill" ]; then
      ln -sfn "$skill" "$dest"
      echo "linked $dest"
    fi
  done
done

for skill in "$skills_dir"/*/; do
  skill="${skill%/}"
  [ -d "$skill" ] || continue
  cmd="$opencode_command_dir/$(basename "$skill").md"

  if [ "$1" = "clean" ] || ! user_only "$skill"; then
    if grep -q "^# generated by skills/install.sh$" "$cmd" 2>/dev/null; then
      rm -f "$cmd"
      echo "removed $cmd"
    fi
    continue
  fi

  description="$(frontmatter "$skill" | sed -n 's/^description:[[:space:]]*//p' | head -1)"
  content="$(cat <<EOF
---
# generated by skills/install.sh
description: $description
---
!\`awk 'f==2{print} /^---\$/{f++}' "$skill/SKILL.md"\`

\$ARGUMENTS
EOF
)"

  if [ "$content" != "$(cat "$cmd" 2>/dev/null)" ]; then
    mkdir -p "$opencode_command_dir"
    printf '%s\n' "$content" > "$cmd"
    echo "wrote $cmd"
  fi
done
